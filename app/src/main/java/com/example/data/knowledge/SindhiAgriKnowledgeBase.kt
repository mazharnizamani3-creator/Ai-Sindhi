    fun findMatchingResponse(query: String): String {
        val clean = query.trim().lowercase()
        for (guide in defaultGuides) {
            val titleMatches = guide.titleSindhi.lowercase().split(" ")
                .any { it.length > 3 && clean.contains(it) }
            val contentMatches = guide.fullContent.lowercase().contains(clean)
            if (titleMatches || contentMatches) {
                return guide.fullContent
            }
        }
        
        if (clean.contains("ڪپهه") || clean.contains("ڦٽي") || clean.contains("cotton")) {
            return defaultGuides[0].fullContent
        }
        if (clean.contains("مکي") || clean.contains("سفيد مکي") || clean.contains("whitefly")) {
            return defaultGuides[1].fullContent
        }
        if (clean.contains("ڪڻڪ") || clean.contains("گندم") || clean.contains("wheat")) {
            return defaultGuides[2].fullContent
        }
        if (clean.contains("چانور") || clean.contains("شالي") || clean.contains("rice")) {
            return defaultGuides[3].fullContent
        }
        if (clean.contains("ڪلر") || clean.contains("لوڻ") || clean.contains("زمين") || clean.contains("salinity")) {
            return defaultGuides[4].fullContent
        }
        if (clean.contains("انب") || clean.contains("سنڌڙي") || clean.contains("mango")) {
            return defaultGuides[5].fullContent
        }
        if (clean.contains("شاهه") || clean.contains("لطيف") || clean.contains("موهن") || clean.contains("اجرڪ") || clean.contains("ثقافت")) {
            return defaultGuides[6].fullContent
        }

        return """
جي سائين! حڪم ڪريو.
توهان جو سوال مون وٽ پهچي ويو آهي. سنڌ جي زرعي مسئلن، فصلن، حشرات (Pest Control)، ٻج، ڀاڻ، يا سنڌي تاريخ ۽ ادب بابت ڪو به خاص تفصيل گهربل هجي ته پڇو، آءٌ هر طرح سان پنهنجي سنڌي ڀائرن جي خدمت لاءِ حاضر آهيان!
        """.trimIndent()
    }
